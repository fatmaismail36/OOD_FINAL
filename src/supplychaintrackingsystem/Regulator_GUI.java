                + "Shipment ID: " + shipmentID + "\n"
                + "Activity Type: " + activityType + "\n"
                + "Record Status: " + recordStatus + "\n"
                + "Result: " + complianceResult + "\n"
                + "Notes: " + notes;

        txtReportSummary.setText(summary);
        auditRecords.add(summary);

        JOptionPane.showMessageDialog(this,
                complianceResult,
                "Compliance Verification",
                JOptionPane.INFORMATION_MESSAGE);

