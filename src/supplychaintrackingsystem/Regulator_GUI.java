private void populateFromUserController() {

    try {

        User currentUser = AppContext.getCurrentUser();

        if (currentUser == null) {
            JOptionPane.showMessageDialog(this, "No logged in user found");
            return;
        }

        Connection con = DBConnection.connect();

        String sql = "SELECT * FROM users WHERE user_id=? AND role='Regulator'";

        PreparedStatement ps = con.prepareStatement(sql);
        ps.setInt(1, currentUser.getUserID());

        ResultSet rs = ps.executeQuery();

        if (rs.next()) {

            txtRegulatorID.setText(rs.getString("user_id"));
            txtAgencyName.setText(rs.getString("full_name"));
            txtAccessLevel.setText(rs.getString("role"));

            if (rs.getString("distribution_area") != null) {
                txtAuditRegion.setText(rs.getString("distribution_area"));
            } else {
                txtAuditRegion.setText("Cairo");
            }

        } else {
            JOptionPane.showMessageDialog(this, "Regulator data not found");
        }

        con.close();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
}


private Regulator ensureRegulator() {
    if (currentRegulator != null) {
        return currentRegulator;
    }

    int regulatorID = parseRequiredInt(txtRegulatorID.getText(), "Regulator ID");
    String agencyName = readRequiredText(txtAgencyName.getText(), "Agency Name");
    String accessLevel = readRequiredText(txtAccessLevel.getText(), "Access Level");
    String auditRegion = readRequiredText(txtAuditRegion.getText(), "Audit Region");

    User baseUser = resolveLoggedInUser();

    if (baseUser != null && regulatorID != baseUser.getUserID()) {
        throw new IllegalArgumentException("Regulator ID must match the logged-in user ID.");
    }

    if (baseUser == null) {
        currentRegulator = new Regulator(
                regulatorID,
                agencyName,
                accessLevel,
                auditRegion,
                regulatorID,
                agencyName,
                "regulator@email.com",
                "password123",
                accessLevel
        );
    } else {
        currentRegulator = new Regulator(
                regulatorID,
                agencyName,
                accessLevel,
                auditRegion,
                baseUser.getUserID(),
                baseUser.getName(),
                baseUser.getEmail(),
                baseUser.getPassword(),
                baseUser.getRole()
        );
    }

    return currentRegulator;
}

private User resolveLoggedInUser() {
    try {
        User currentUser = AppContext.getCurrentUser();

        if (currentUser == null) {
            return null;
        }

        if (userController == null) {
            return currentUser;
        }

        User storedUser = userController.getUser(currentUser.getUserID());
        return storedUser != null ? storedUser : currentUser;

    } catch (Exception ex) {
        return null;
    }
}

private int parseRequiredInt(String value, String fieldName) {
    String text = value == null ? "" : value.trim();

    if (text.isBlank() || text.startsWith("jTextField")) {
        throw new IllegalArgumentException(fieldName + " cannot be empty.");
    }

    if (!text.matches("\\d+")) {
        throw new IllegalArgumentException(fieldName + " must contain numbers only.");
    }

    int number = Integer.parseInt(text);

    if (number <= 0) {
        throw new IllegalArgumentException(fieldName + " must be greater than 0.");
    }

    return number;
}

private String readRequiredText(String value, String fieldName) {
    String text = value == null ? "" : value.trim();

    if (text.isBlank() || text.startsWith("jTextField")) {
        throw new IllegalArgumentException(fieldName + " cannot be empty.");
    }

    return text;
}
