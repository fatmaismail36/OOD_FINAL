    private void btnAddtoInventoryActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddtoInventoryActionPerformed
 try {
        int productID = parseRequiredInt(txtProductID.getText(), "Product ID");
        int quantity = parseRequiredInt(txtQuantity.getText(), "Quantity");

        Product product = findProductByID(productID);

        if (product == null) {
            throw new IllegalArgumentException("Product must be added before adding it to inventory.");
        }

        String qualityStatus = product.getStatus();

        if (!"Approved".equalsIgnoreCase(qualityStatus)) {
            throw new IllegalStateException("Only approved products can be added to inventory.");
        }

        Inventory inventory = findInventoryByProductID(productID);

        if (inventory == null) {
            inventory = new Inventory();
            inventory.setProductID(product.getProductID());
            inventory.setProductName(product.getProductName());
            inventory.setProduct(product);
            inventory.setWarehouseLocation("Manufacturer Warehouse");
            inventory.setStockLevel(quantity);
            product.setInventory(inventory);
            inventoryRecords.add(inventory);
        } else {
            inventory.addStock(quantity);
        }

        String message =
                "Product Added to Inventory\n"
                + "Product ID: " + product.getProductID() + "\n"
                + "Product Name: " + product.getProductName() + "\n"
                + "Quantity Added: " + quantity + "\n"
                + "Current Stock Level: " + inventory.getStockLevel() + "\n"
                + "Availability: " + inventory.getAvailability() + "\n"
                + "Stock Condition: " + inventory.getStockCondition();

        JOptionPane.showMessageDialog(this,
                message,
                "Add to Inventory",
                JOptionPane.INFORMATION_MESSAGE);

    } catch (IllegalArgumentException | IllegalStateException ex) {
        JOptionPane.showMessageDialog(this,
                ex.getMessage(),
                "Validation Error",
                JOptionPane.ERROR_MESSAGE);
    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this,
                "Unexpected error while adding to inventory: " + ex.getMessage(),
                "Inventory Error",
                JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnAddtoInventoryActionPerformed

    private void btnReportIssueActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnReportIssueActionPerformed
 try {
        int productID = parseRequiredInt(txtProductID.getText(), "Product ID");
        String issue = readRequiredText(txtProductNotes.getText(), "Product Notes / Issue Report");

        if (isDefaultNotes(issue)) {
            throw new IllegalArgumentException("Please enter a real issue report.");
        }

        Product product = findProductByID(productID);

        if (product == null) {
            throw new IllegalArgumentException("Product ID was not found.");
        }

        product.setIssueReport(issue);
        product.setStatus("Rejected");

        cmbQualityStatus.setSelectedItem("Rejected");

        String message =
                "Product Issue Reported\n"
                + "Product ID: " + product.getProductID() + "\n"
                + "Product Name: " + product.getProductName() + "\n"
                + "Issue: " + issue + "\n"
                + "New Quality Status: Rejected";

        JOptionPane.showMessageDialog(this,
                message,
                "Report Issue",
                JOptionPane.WARNING_MESSAGE);

    } catch (IllegalArgumentException ex) {
        JOptionPane.showMessageDialog(this,
                ex.getMessage(),
                "Validation Error",
                JOptionPane.ERROR_MESSAGE);
    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this,
                "Unexpected error while reporting issue: " + ex.getMessage(),
                "Product Error",
                JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnReportIssueActionPerformed

