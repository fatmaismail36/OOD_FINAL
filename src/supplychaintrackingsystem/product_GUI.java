    private void btnAddProductActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddProductActionPerformed
try {
        String productName = readRequiredText(txtProductName.getText(), "Product Name");
        String category = (String) cmbCategory.getSelectedItem();
        int supplierID = parseRequiredInt(txtRawMaterialSupplierID.getText(), "Raw Material Supplier ID");
        double price = parseRequiredDouble(txtPrice.getText(), "Price");
        int quantity = parseRequiredInt(txtQuantity.getText(), "Quantity");
        Date manufactureDate = parseRequiredDate(ManufactureDate.getText(), "Manufacture Date");
        Date expiryDate = parseRequiredDate(txtExpiryDate.getText(), "Expiry Date");
        String qualityStatus = (String) cmbQualityStatus.getSelectedItem();
        String notes = getNotesText();

        if (!expiryDate.after(manufactureDate)) {
            throw new IllegalArgumentException("Expiry Date must be after Manufacture Date.");
        }

        Product product = new Product();
        product.setProductName(productName);
        product.setCategory(category);
        product.setUnitPrice(price);
        product.setManufactureDate(manufactureDate);
        product.setExpiryDate(expiryDate);
        product.setStatus(qualityStatus);
        product.setIssueReport(notes);

        products.add(product);

        if (currentManufacturer != null) {
            currentManufacturer.startProduction(product);
            currentManufacturer.completeProduction(product, quantity);
        }

        txtProductID.setText(String.valueOf(product.getProductID()));

        String message =
                "Product Added Successfully\n"
                + "Product ID: " + product.getProductID() + "\n"
                + "Product Name: " + product.getProductName() + "\n"
                + "Category: " + product.getCategory() + "\n"
                + "Raw Material Supplier ID: " + supplierID + "\n"
                + "Price: " + product.getUnitPrice() + "\n"
                + "Quantity: " + quantity + "\n"
                + "Quality Status: " + product.getStatus();

        JOptionPane.showMessageDialog(this,
                message,
                "Add Product",
                JOptionPane.INFORMATION_MESSAGE);

    } catch (IllegalArgumentException ex) {
        JOptionPane.showMessageDialog(this,
                ex.getMessage(),
                "Validation Error",
                JOptionPane.ERROR_MESSAGE);
    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this,
                "Unexpected error while adding product: " + ex.getMessage(),
                "Product Error",
                JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnAddProductActionPerformed

