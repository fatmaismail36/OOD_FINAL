private Product findProductByID(int productID) {
    for (Product product : products) {
        if (product.getProductID() == productID) {
            return product;
        }
    }
    return null;
}

private Inventory findInventoryByProductID(int productID) {
    for (Inventory inventory : inventoryRecords) {
        if (inventory.getProductID() == productID) {
            return inventory;
        }
    }
    return null;
}

private int parseRequiredInt(String value, String fieldName) {
    String text = value == null ? "" : value.trim();

    if (text.isBlank()) {
        throw new IllegalArgumentException(fieldName + " cannot be empty.");
    }

    if (!text.matches("\\d+")) {
        throw new IllegalArgumentException(fieldName + " must contain numbers only.");
    }

    int number = Integer.parseInt(text);

    if (number <= 0) {
        throw new IllegalArgumentException(fieldName + " must be greater than 0.");
    }

    return number;
}

private double parseRequiredDouble(String value, String fieldName) {
    String text = value == null ? "" : value.trim();

    if (text.isBlank()) {
        throw new IllegalArgumentException(fieldName + " cannot be empty.");
    }

    try {
        double number = Double.parseDouble(text);

        if (number <= 0) {
            throw new IllegalArgumentException(fieldName + " must be greater than 0.");
        }

        return number;

    } catch (NumberFormatException ex) {
        throw new IllegalArgumentException(fieldName + " must be a valid number.");
    }
}

private String readRequiredText(String value, String fieldName) {
    String text = value == null ? "" : value.trim();

    if (text.isBlank()) {
        throw new IllegalArgumentException(fieldName + " cannot be empty.");
    }

    return text;
}

private Date parseRequiredDate(String value, String fieldName) {
    String text = readRequiredText(value, fieldName);

    try {
        SimpleDateFormat formatter = new SimpleDateFormat("yyyy-MM-dd");
        formatter.setLenient(false);
        return formatter.parse(text);
    } catch (ParseException ex) {
        throw new IllegalArgumentException(fieldName + " must be in format yyyy-MM-dd.");
    }
}

private String getNotesText() {
    String notes = txtProductNotes.getText();

    if (notes == null || isDefaultNotes(notes)) {
        return "";
    }

    return notes.trim();
}

private boolean isDefaultNotes(String text) {
    if (text == null) {
        return true;
    }

    return text.trim().equalsIgnoreCase("Enter notes, issues or important information about the product..");
}
